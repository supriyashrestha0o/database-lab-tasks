SELECT E.FNAME, E.LNAME,
E.SALARY * 1.1 AS increased_salary
FROM EMPLOYEE E
JOIN DEPARTMENT D ON E.DNO = D.DNUMBER
WHERE D.DNAME = 'Research';


SELECT SUM(E.SALARY) AS Total,
MAX(E.SALARY) AS max,
MIN(E.SALARY) AS min,
AVG(E.SALARY) AS average
FROM EMPLOYEE E
JOIN DEPARTMENT D ON E.DNO = D.DNUMBER
WHERE D.DNAME = 'Administration';


SELECT FNAME, LNAME
FROM EMPLOYEE
